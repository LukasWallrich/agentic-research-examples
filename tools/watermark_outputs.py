#!/usr/bin/env python3
"""Mark every manuscript and cover letter of the examples as an AI-generated demonstration.

- PDF: a diagonal, semi-transparent watermark on every page and a footer line.
- HTML: a fixed banner at the top of the page.
- DOCX: a header on every page and a banner as the first paragraph.
- Markdown and Quarto sources: a banner at the top (a YAML comment inside the front matter,
  so the file still renders, followed by a visible banner in the body).
- LaTeX: a comment block at the top.
- Writes AI_GENERATED.md into each example folder.

Usage (from the repository root):
    uv run --with reportlab --with pypdf --with python-docx python tools/watermark_outputs.py

Files that already carry the mark are left unchanged, so reruns are safe.
The unmarked originals stay in the imported commits (see ORIGINAL_COMMIT).
"""

import io
import re
from pathlib import Path

from docx import Document
from docx.shared import Pt, RGBColor
from pypdf import PdfReader, PdfWriter
from reportlab.lib.colors import Color
from reportlab.pdfgen import canvas

REPO = Path(__file__).resolve().parent.parent
MARK = "AI-GENERATED DEMONSTRATION — NOT PEER REVIEWED — NOT FOR CITATION"
REPO_NAME = "agentic-research-examples"
FOOTER = f"{REPO_NAME}: AI-generated demonstration for the tutorial \"Easing into agentic AI in research\". See AI_GENERATED.md."
PDF_FLAG = "/AIGeneratedDemonstration"

ORIGINAL_COMMIT = {
    "anchoring-extremity-opaq": "89c45f5",
    "selective-feedback-simulation": "61ace46",
    "confidence-weighting-crowds": "4afe867",
}

FILES = {
    "anchoring-extremity-opaq": ["manuscript/manuscript.pdf", "manuscript/manuscript.html",
                                 "manuscript/manuscript.docx", "manuscript/manuscript.qmd",
                                 "manuscript/cover_letter.md"],
    "selective-feedback-simulation": ["manuscript/manuscript.pdf", "manuscript/manuscript.html",
                                      "manuscript/manuscript.md", "manuscript/manuscript.template.md",
                                      "manuscript/manuscript.tex", "manuscript/cover_letter.html",
                                      "manuscript/cover_letter.md"],
    "confidence-weighting-crowds": ["manuscript/manuscript.pdf", "manuscript/manuscript.html",
                                    "manuscript/manuscript.md", "manuscript/cover_letter.md"],
}

AI_GENERATED = """# AI-generated demonstration

> **Warning.** All research content in this folder (study design, code, analyses, manuscript, cover letter
> and reviews) was generated by AI agents from a single brief. It is a demonstration of task completion
> for the tutorial "Easing into agentic AI in research". It has not been peer reviewed, and its scientific
> quality has not been evaluated. It is not intended for publication or for citation as research findings.
> Errors are known to exist: see [`weaknesses.md`](weaknesses.md) and [`deviations.md`](deviations.md).

The manuscript files in `manuscript/` carry a watermark or banner with this warning. The unwatermarked files
are in commit `{commit}`, for example `git show {commit}:manuscript/manuscript.pdf > manuscript_original.pdf`.
"""


def pdf_stamp(width, height):
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=(width, height))
    c.saveState()
    c.setFillColor(Color(0.8, 0.0, 0.0, alpha=0.25))
    c.translate(width / 2, height / 2)
    c.rotate(55)
    c.setFont("Helvetica-Bold", 34)
    parts = MARK.split(" — ")
    for i, part in enumerate(parts):
        c.drawCentredString(0, (len(parts) / 2 - i - 0.5) * 44, part)
    c.restoreState()
    c.setFillColor(Color(0.6, 0.0, 0.0, alpha=0.9))
    c.setFont("Helvetica", 7)
    c.drawCentredString(width / 2, 12, FOOTER)
    c.save()
    return PdfReader(io.BytesIO(buf.getvalue())).pages[0]


def mark_pdf(path):
    reader = PdfReader(path)
    if reader.metadata and PDF_FLAG in reader.metadata:
        return False
    writer = PdfWriter(clone_from=reader)
    for page in writer.pages:
        box = page.mediabox
        stamp = pdf_stamp(float(box.width), float(box.height))
        page.merge_translated_page(stamp, float(box.left), float(box.bottom), over=True)
    writer.add_metadata({PDF_FLAG: MARK})
    with open(path, "wb") as fh:
        writer.write(fh)
    return True


HTML_BANNER = (
    '<div id="ai-generated-banner" style="position:fixed;top:0;left:0;right:0;z-index:99999;'
    'background:#b00020;color:#fff;font:bold 15px/1.4 sans-serif;text-align:center;padding:8px 12px;">'
    f'{MARK}<br><span style="font-weight:normal;font-size:12px;">{FOOTER}</span></div>'
    '<div style="height:64px"></div>'
)


def mark_html(path):
    text = path.read_text(encoding="utf-8")
    if 'id="ai-generated-banner"' in text:
        return False
    m = re.search(r"<body[^>]*>", text)
    if not m:
        raise SystemExit(f"no <body> tag in {path}")
    path.write_text(text[:m.end()] + HTML_BANNER + text[m.end():], encoding="utf-8")
    return True


def mark_docx(path):
    doc = Document(path)
    if doc.paragraphs and MARK in doc.paragraphs[0].text:
        return False
    for section in doc.sections:
        headers = [section.header]
        if section.different_first_page_header_footer:
            headers.append(section.first_page_header)
        if doc.settings.odd_and_even_pages_header_footer:
            headers.append(section.even_page_header)
        for header in headers:
            header.is_linked_to_previous = False
            para = header.paragraphs[0].insert_paragraph_before() if header.paragraphs else header.add_paragraph()
            run = para.add_run(MARK)
            run.bold = True
            run.font.size = Pt(9)
            run.font.color.rgb = RGBColor(0xB0, 0x00, 0x20)
    first = doc.paragraphs[0].insert_paragraph_before()
    run = first.add_run(f"{MARK}. {FOOTER}")
    run.bold = True
    run.font.color.rgb = RGBColor(0xB0, 0x00, 0x20)
    doc.save(path)
    return True


MD_BANNER = f"> **{MARK}.** {FOOTER}\n\n"


def mark_markdown(path):
    text = path.read_text(encoding="utf-8")
    if MARK in text:
        return False
    if text.startswith("---\n"):
        end = text.index("\n---\n", 4) + len("\n---\n")
        front = "---\n" + f"# {MARK}. See AI_GENERATED.md in the example folder.\n" + text[4:end]
        text = front + "\n" + MD_BANNER + text[end:].lstrip("\n")
    else:
        text = MD_BANNER + text
    path.write_text(text, encoding="utf-8")
    return True


def mark_tex(path):
    text = path.read_text(encoding="utf-8")
    if MARK in text:
        return False
    path.write_text(f"% {MARK}\n% {FOOTER}\n" + text, encoding="utf-8")
    return True


def main():
    for folder, files in FILES.items():
        base = REPO / folder
        (base / "AI_GENERATED.md").write_text(AI_GENERATED.format(commit=ORIGINAL_COMMIT[folder]),
                                              encoding="utf-8")
        for rel in files:
            path = base / rel
            name = path.name
            if name.endswith(".pdf"):
                changed = mark_pdf(path)
            elif name.endswith(".html"):
                changed = mark_html(path)
            elif name.endswith(".docx"):
                changed = mark_docx(path)
            elif name.endswith(".tex"):
                changed = mark_tex(path)
            else:
                changed = mark_markdown(path)
            print(f"{'marked ' if changed else 'already'} {folder}/{rel}")


if __name__ == "__main__":
    main()
